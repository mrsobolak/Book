"""HORNET RPL: shoulder-fired recoilless launcher with an 85 mm HE rocket loaded."""
from lib import *


def build():
    # ---- launch tube, venturi, heat guard, shoulder sleeve
    lathe("Tube", [(-0.462, 0.0195), (-0.462, 0.0220), (0.360, 0.0220), (0.360, 0.0195)], "Paint", seg=64, closed=True,
          bev=0.0006, segs=2)
    lathe("MuzzleRing", [(0.344, 0.0195), (0.344, 0.0248), (0.370, 0.0248), (0.372, 0.0232), (0.372, 0.0195)], "Steel",
          seg=64, closed=True, bev=0.0005, segs=2)
    lathe("Venturi", [(-0.460, 0.0195), (-0.460, 0.0238), (-0.520, 0.0300), (-0.600, 0.0430), (-0.628, 0.0465),
                      (-0.636, 0.0465), (-0.636, 0.0425), (-0.600, 0.0395), (-0.540, 0.0260), (-0.500, 0.0170),
                      (-0.470, 0.0170)], "Steel", seg=72, closed=True, bev=0.0006, segs=2)
    sl = [(-0.400, 0.0220), (-0.400, 0.0262)]
    x = -0.396
    while x < -0.295:
        sl += [(x, 0.0262), (x + 0.002, 0.0270), (x + 0.008, 0.0270), (x + 0.010, 0.0262)]
        x += 0.012
    sl += [(-0.288, 0.0262), (-0.288, 0.0220)]
    lathe("ShoulderSleeve", sl, "Rubber", seg=64, closed=True)
    hg = [(-0.200, 0.0220), (-0.200, 0.0292)]
    x = -0.196
    while x < 0.096:
        t = (x + 0.05) / 0.15
        r = 0.0305 + 0.0010 * (1 - t * t)
        hg += [(x, r), (x + 0.026, r), (x + 0.027, r - 0.0012), (x + 0.029, r - 0.0012), (x + 0.030, r)]
        x += 0.030
    hg += [(0.100, 0.0292), (0.100, 0.0220)]
    lathe("HeatGuard", hg, "Wood", seg=72, closed=True, bev=0.0008, segs=2)
    for x in (-0.206, 0.100):
        lathe(f"Band{x}", [(x, 0.0220), (x, 0.0325), (x + 0.008, 0.0325), (x + 0.008, 0.0220)], "Steel", seg=64,
              closed=True, bev=0.0006, segs=2)

    # ---- rocket
    rk = [(0.300, 0), (0.300, 0.0188), (0.400, 0.0188), (0.470, 0.0430), (0.530, 0.0430)]
    for i in range(1, 9):
        t = i / 8
        rk.append((0.530 + 0.090 * t, 0.0120 + (0.0430 - 0.0120) * math.cos(t * math.pi / 2) ** 0.8))
    rk += [(0.640, 0.0120), (0.640, 0)]
    lathe("Warhead", rk, "Warhead", seg=72, bev=0.0006, segs=2)
    lathe("HEBand", [(0.494, 0.0428), (0.494, 0.0434), (0.510, 0.0434), (0.510, 0.0428)], "Stripe", seg=72, closed=True)
    lathe("Fuze", [(0.636, 0), (0.636, 0.0118), (0.650, 0.0110), (0.656, 0.0068), (0.660, 0.0040), (0.660, 0)], "Steel",
          seg=40, bev=0.0004, segs=1)

    # ---- trigger housing, grips
    th = prism("TriggerHousing", path([("M", -0.140, -0.019), ("L", 0.000, -0.019), ("L", 0.000, -0.034),
                                       ("Q", (-0.002, -0.064), (-0.016, -0.066), 5), ("L", -0.048, -0.064),
                                       ("Q", (-0.060, -0.063), (-0.064, -0.052), 4), ("L", -0.070, -0.040),
                                       ("L", -0.130, -0.036), ("Q", (-0.140, -0.034), (-0.140, -0.019), 3)]),
               0.0, 0.030, "Paint", bev=0.0012, segs=2)
    bm = bmesh.new(); bm_prism(bm, rrect(-0.054, -0.058, -0.006, -0.034, 0.006), 0.0, 0.05); cut(th, bm)
    ar_grip("Grip", -0.002, -0.004, mat="Polymer")
    ar_trigger("Trigger", -0.002, 0.002)
    selector(-0.100, -0.028, -0.0150)
    lathe("ForeClamp", [(0.168, 0.0220), (0.168, 0.0262), (0.194, 0.0262), (0.194, 0.0220)], "Steel", seg=64, closed=True,
          bev=0.0005, segs=1)
    prism("ForeBlock", rrect(0.168, -0.036, 0.194, -0.020, 0.003), 0.0, 0.022, "Steel", bev=0.0008, segs=2)
    vg = [(-0.122, 0), (-0.122, 0.0118), (-0.120, 0.0137), (-0.114, 0.0142)]
    z = -0.107
    while z < -0.058:
        vg += [(z, 0.0140), (z + 0.0015, 0.0133), (z + 0.0045, 0.0133), (z + 0.006, 0.0138)]
        z += 0.0075
    vg += [(-0.050, 0.0128), (-0.040, 0.0131), (-0.037, 0.0124), (-0.034, 0.0105), (-0.034, 0)]
    lathe("ForeGrip", vg, "Polymer", seg=48, axis="Z", c=(0.181, 0, 0), bev=0.0005, segs=2)

    # ---- iron sights + side-mounted optic
    prism("FrontSight", path([("M", -0.006, 0.020), ("L", 0.006, 0.020), ("L", 0.006, 0.050), ("L", 0.004, 0.052),
                              ("L", 0.0035, 0.038), ("L", 0.0012, 0.036), ("L", 0.0012, 0.048), ("L", -0.0012, 0.048),
                              ("L", -0.0012, 0.036), ("L", -0.0035, 0.038), ("L", -0.004, 0.052), ("L", -0.006, 0.050)]),
          0.300, 0.005, "Steel", plane="YZ", bev=0.0004, segs=1)
    rs = prism("RearSight", rrect(-0.010, 0.020, 0.010, 0.050, 0.003), -0.040, 0.004, "Steel", plane="YZ",
               bev=0.0004, segs=1)
    bm = bmesh.new(); bm_box(bm, -0.05, -0.03, -0.0022, 0.0022, 0.040, 0.06); cut(rs, bm)
    prism("OpticPlate", rrect(-0.200, -0.010, -0.060, 0.032, 0.006), -0.0245, 0.006, "Paint", bev=0.0010, segs=2)
    prism("OpticArm", rrect(-0.175, 0.012, -0.095, 0.030, 0.004), -0.040, 0.026, "Paint", bev=0.0010, segs=2)
    OY, OZ = -0.058, 0.040
    lathe("OpticTube", [(-0.212, 0), (-0.212, 0.0135), (-0.205, 0.0140), (-0.080, 0.0140), (-0.070, 0.0180),
                        (-0.052, 0.0180), (-0.050, 0.0168), (-0.050, 0.0150), (-0.056, 0.0150), (-0.056, 0)],
          "Optic", seg=56, c=(0, OY, OZ), bev=0.0005, segs=2)
    lathe("EyeCup", [(-0.246, 0.0130), (-0.246, 0.0200), (-0.236, 0.0200), (-0.212, 0.0158), (-0.212, 0.0130)],
          "Rubber", seg=56, c=(0, OY, OZ), closed=True, bev=0.0010, segs=2)
    bm = bmesh.new()
    bm_lathe(bm, [(-0.0555, 0), (-0.0555, 0.0150), (-0.0545, 0.0150), (-0.0545, 0)], 48, "X", (0, OY, OZ))
    bm_lathe(bm, [(-0.2125, 0), (-0.2125, 0.0130), (-0.2115, 0.0130), (-0.2115, 0)], 48, "X", (0, OY, OZ))
    mk("OpticLenses", bm, "Glass")
    lathe("OpticKnob", [(0, 0), (0, 0.0080), (0.008, 0.0080), (0.009, 0.0068), (0.009, 0)], "Optic", seg=32, axis="Z",
          c=(-0.140, OY, OZ + 0.013), bev=0.0004, segs=1)

    text("HORNET RPL", 0.0060, -0.070, -0.030, -0.01505, "MarkName")
    text("85 MM HE  HALVARD", 0.0028, -0.070, -0.0365, -0.01505, "MarkCal")
