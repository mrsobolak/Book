"""RAVEN: seven-inch clip-point combat knife."""
from lib import *


def build():
    L = 0.178
    st = []
    N = 44
    for i in range(N + 1):
        x = L * i / N
        zs = 0.019 if x <= 0.110 else 0.019 - 0.015 * ((x - 0.110) / (L - 0.110)) ** 0.9
        ze = -0.013 if x <= 0.100 else -0.013 + 0.017 * ((x - 0.100) / (L - 0.100)) ** 1.8
        zg = ze + min(0.0030, 0.3 * (zs - ze))
        ts = 0.0025 if x <= 0.110 else 0.0025 * (1 - 0.82 * (x - 0.110) / (L - 0.110))
        tg = 0.00045 * (1 - 0.5 * max(0.0, (x - 0.14) / (L - 0.14)))
        st.append((x, ze, zg, zs, tg, ts))
    bl = blade("Blade", st)
    bm = bmesh.new()
    for s in (1, -1):
        bm_rod(bm, (0.020, s * 0.0043, 0.0080), (0.092, s * 0.0043, 0.0080), 0.0027, seg=24, rounded=True)
    cut(bl, bm)

    prism("Guard", path([("M", -0.007, 0.024), ("Q", (0.000, 0.025), (0.000, 0.020), 3), ("L", 0.000, -0.018),
                         ("Q", (0.004, -0.029), (0.010, -0.034), 4), ("Q", (0.013, -0.039), (0.007, -0.040), 3),
                         ("Q", (-0.004, -0.037), (-0.007, -0.024), 4)]), 0.0, 0.020, "Steel", bev=0.0014, segs=2)
    handle = path([("M", -0.006, 0.017), ("L", -0.030, 0.018), ("Q", (-0.060, 0.021), (-0.090, 0.017), 8),
                   ("Q", (-0.108, 0.015), (-0.114, 0.012), 4), ("L", -0.114, -0.016), ("Q", (-0.100, -0.024), (-0.088, -0.020), 4),
                   ("Q", (-0.075, -0.013), (-0.062, -0.022), 5), ("Q", (-0.050, -0.029), (-0.036, -0.020), 5),
                   ("Q", (-0.024, -0.013), (-0.012, -0.022), 5), ("Q", (-0.006, -0.024), (-0.006, -0.016), 3)])
    prism("Handle", handle, 0.0, 0.026, "Grip", bev=0.0060, segs=3)
    pm = prism("Pommel", path([("M", -0.112, 0.014), ("L", -0.124, 0.014), ("Q", (-0.132, 0.012), (-0.136, 0.004), 3),
                               ("L", -0.143, -0.001), ("L", -0.136, -0.006), ("Q", (-0.130, -0.018), (-0.120, -0.020), 3),
                               ("L", -0.112, -0.018)]), 0.0, 0.022, "Steel", bev=0.0016, segs=2)
    bm = bmesh.new(); bm_prism(bm, circle(-0.123, -0.004, 0.0030, 24), 0.0, 0.05); cut(pm, bm)
    bm = bmesh.new()
    for x in (-0.034, -0.084):
        for s in (1, -1):
            vs = bm_lathe(bm, [(0, 0), (0, 0.0036), (0.0010, 0.0036), (0.0014, 0.0029), (0.0014, 0)], 24, "Y", (x, 0.0118, 0.000))
            if s < 0: mirror_y(vs)
    sc = mk("Screws", bm, "Steel", bev=0.0002, segs=1)
    bm = bmesh.new()
    for x in (-0.034, -0.084):
        for s in (1, -1):
            bm_prism(bm, circle(x, 0.0, 0.0015, 6), s * 0.0134, 0.0020)
    cut(sc, bm)
    text("RAVEN", 0.0050, 0.032, 0.0118, -0.00210, "MarkName")
    text("1095  NORTHLINE", 0.0024, 0.032, 0.0118, 0.00210, "MarkMaker")
