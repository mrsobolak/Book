"""TALON-B: bullpup marksman rifle with a full-hand trigger guard and a 1-6x LPVO."""
from lib import *


def build():
    # ---- one-piece polymer shell
    shell = path([
        ("M", -0.395, 0.030), ("L", 0.200, 0.030), ("Q", (0.212, 0.030), (0.212, 0.018), 3), ("L", 0.212, -0.030),
        ("Q", (0.212, -0.042), (0.200, -0.043), 3), ("L", 0.172, -0.045), ("Q", (0.180, -0.100), (0.150, -0.128), 8),
        ("L", 0.040, -0.135), ("Q", (0.000, -0.136), (-0.012, -0.110), 6), ("L", -0.022, -0.060),
        ("L", -0.215, -0.060), ("Q", (-0.300, -0.070), (-0.390, -0.105), 8), ("L", -0.395, -0.100),
    ])
    def taper(x, z):
        s = 1.0 - 0.06 * smoothstep(0.0, 0.03, z)
        if x > -0.03:
            s *= 1.0 - 0.45 * smoothstep(-0.047, -0.066, z)
        return s
    sh = prism("Shell", shell, 0.0, 0.056, "Polymer", taper=taper, bev=0.0028, segs=3)
    bm = bmesh.new()
    bm_prism(bm, rrect(0.002, -0.122, 0.158, -0.052, 0.018), 0.0, 0.08)                      # hand loop
    bm_prism(bm, rrect(-0.205, -0.0115, -0.140, 0.0115, 0.002), -0.045, 0.07, plane="XY")      # magwell
    bm_prism(bm, rrect(-0.222, -0.006, -0.140, 0.018, 0.004), 0.028, 0.016)                   # ejection port
    bm_prism(bm, rrect(-0.222, -0.006, -0.140, 0.018, 0.004), -0.0285, 0.003)                 # ambi cover recess
    cut(sh, bm)
    prism("EjectCover", rrect(-0.219, -0.003, -0.143, 0.015, 0.003), -0.0268, 0.0015, "Polymer", bev=0.0005, segs=1)
    bm = bmesh.new()
    for s in (1, -1):
        bm_prism(bm, path([("M", -0.350, -0.050), ("L", -0.250, -0.050), ("Q", (-0.238, -0.050), (-0.238, -0.038), 3),
                           ("L", -0.238, 0.004), ("Q", (-0.238, 0.014), (-0.250, 0.014), 3), ("L", -0.350, 0.014),
                           ("Q", (-0.362, 0.014), (-0.362, 0.002), 3), ("L", -0.362, -0.062)]), s * 0.0272, 0.0016)
    mk("CheekPanels", bm, "Grip", bev=0.0005, segs=1)
    rail("TopRail", -0.300, 0.205, 0.028, zt=0.0385)
    prism("ButtPad", rrect(-0.409, -0.106, -0.394, 0.032, 0.006), 0.0, 0.058, "Rubber", bev=0.003, segs=3)

    grip = path([("M", 0.045, -0.046), ("L", 0.085, -0.046), ("Q", (0.080, -0.066), (0.084, -0.074), 4),
                 ("Q", (0.074, -0.086), (0.080, -0.096), 5), ("Q", (0.070, -0.106), (0.074, -0.114), 4),
                 ("L", 0.068, -0.122), ("L", 0.030, -0.122)])
    prism("Grip", grip, 0.0, 0.030, "Grip", bev=0.0024, segs=3)
    prism("Trigger", path([("M", 0.097, -0.050), ("L", 0.103, -0.050), ("Q", (0.107, -0.064), (0.103, -0.076), 5),
                           ("Q", (0.101, -0.079), (0.098, -0.076), 3), ("L", 0.096, -0.064)]), 0.0, 0.0045, "Steel",
          bev=0.0005, segs=2)
    selector(0.018, -0.036, -0.0262)

    # ---- magazine behind the grip
    prism("Mag", [(-0.203, -0.020), (-0.142, -0.020), (-0.137, -0.150), (-0.198, -0.155)], 0.0, 0.023, "Polymer",
          bev=0.0012, segs=2)
    prism("MagFloor", [(-0.201, -0.152), (-0.134, -0.147), (-0.134, -0.156), (-0.201, -0.162)], 0.0, 0.027, "Polymer",
          bev=0.0015, segs=2)
    bm = bmesh.new()
    for k in range(3):
        z = -0.105 - 0.013 * k
        for s in (1, -1):
            bm_prism(bm, [(-0.194, z), (-0.146, z + 0.0015), (-0.146, z + 0.0045), (-0.194, z + 0.003)], s * 0.0118, 0.0012)
    mk("MagRibs", bm, "Polymer", bev=0.0003, segs=1)

    # ---- barrel + 3-prong flash hider, charging handle
    lathe("Barrel", [(0.190, 0), (0.190, 0.0095), (0.440, 0.0095), (0.440, 0)], "Steel", seg=36)
    fh = lathe("FlashHider", [(0.435, 0), (0.435, 0.0105), (0.438, 0.0118), (0.492, 0.0118), (0.496, 0.0106),
                              (0.496, 0.0060), (0.450, 0.0060), (0.450, 0)], "Steel", seg=40, bev=0.0004, segs=2)
    bm = bmesh.new()
    for k in range(3):
        vs = bm_box(bm, 0.462, 0.500, -0.0022, 0.0022, 0.003, 0.02)
        rotate_verts(bm, vs, 90 + 120 * k, "X", (0, 0, 0))
    cut(fh, bm)
    rod("ChargingArm", (0.150, -0.026, 0.012), (0.150, -0.042, 0.012), 0.0030, "Steel", seg=16)
    rod("ChargingKnob", (0.150, -0.040, 0.012), (0.150, -0.053, 0.012), 0.0056, "Polymer", seg=24, rounded=True)
    lathe("SlingQD", [(0, 0.0032), (0, 0.006), (-0.0018, 0.006), (-0.0018, 0.0032)], "Steel", seg=28, axis="Y",
          c=(0.185, -0.0275, -0.020), closed=True)

    # ---- 1-6x LPVO in a cantilever mount
    OZ = 0.0725
    prof = [(-0.250, 0), (-0.250, 0.0165), (-0.257, 0.0165), (-0.257, 0.0180), (-0.255, 0.0205), (-0.215, 0.0205),
            (-0.205, 0.0150), (0.030, 0.0150), (0.050, 0.0195), (0.095, 0.0195), (0.097, 0.0180), (0.097, 0.0170),
            (0.090, 0.0170), (0.090, 0)]
    lathe("LPVOTube", prof, "Optic", seg=64, c=(0, 0, OZ), bev=0.0005, segs=2)
    bm = bmesh.new()
    bm_lathe(bm, [(0.0905, 0), (0.0905, 0.0170), (0.0915, 0.0170), (0.0915, 0)], 48, "X", (0, 0, OZ))
    bm_lathe(bm, [(-0.2505, 0), (-0.2505, 0.0165), (-0.2495, 0.0165), (-0.2495, 0)], 48, "X", (0, 0, OZ))
    mk("LPVOLenses", bm, "Glass")
    ring = [(-0.196, 0.0150), (-0.196, 0.0172)]
    x = -0.194
    while x < -0.170:
        ring += [(x, 0.0172), (x + 0.0008, 0.0180), (x + 0.0022, 0.0180), (x + 0.003, 0.0172)]
        x += 0.0035
    ring += [(-0.168, 0.0172), (-0.168, 0.0150)]
    lathe("MagRing", ring, "Optic", seg=64, c=(0, 0, OZ), closed=True)
    bm = bmesh.new()
    vs = bm_prism(bm, rrect(-0.186, -0.003, -0.178, 0.016, 0.003), 0.0, 0.004, plane="XZ")
    for v in vs: v.co.z += OZ + 0.013
    rotate_verts(bm, vs, 40, "X", (0, 0, OZ))
    mk("ThrowLever", bm, "Optic", bev=0.0008, segs=2)
    tur = [(0, 0), (0, 0.0095), (0.003, 0.0095)]
    z = 0.003
    while z < 0.011:
        tur += [(z, 0.0100), (z + 0.001, 0.0100), (z + 0.0015, 0.0095)]
        z += 0.0015
    tur += [(0.012, 0.0095), (0.013, 0.0085), (0.013, 0)]
    lathe("TurretTop", tur, "Optic", seg=40, axis="Z", c=(-0.080, 0, OZ + 0.0135))
    lathe("TurretRight", tur, "Optic", seg=40, axis="Y", c=(-0.080, 0.0135, OZ))
    bm = bmesh.new(); vs = bm_lathe(bm, tur, 40, "Y", (-0.080, 0.0135, OZ)); mirror_y(vs)
    mk("TurretLeft", bm, "Optic")
    prism("LPVOSaddle", rrect(-0.018, OZ - 0.018, 0.018, OZ + 0.018, 0.007), -0.080, 0.030, "Optic", plane="YZ",
          bev=0.0012, segs=2)
    clamp = [(-0.0125, 0.0345), (0.0125, 0.0345), (0.0125, 0.044), (0.008, 0.050), (-0.008, 0.050), (-0.0125, 0.044)]
    prism("MountBase", clamp, -0.050, 0.110, "Optic", plane="YZ", bev=0.0010, segs=2)
    for x in (-0.100, 0.000):
        bm = bmesh.new()
        bm_tube(bm, circle(0, OZ, 0.0195, 48), circle(0, OZ, 0.0150, 48), x - 0.007, x + 0.007)
        mk(f"Ring{x}", bm, "Optic", bev=0.0006, segs=2)
        prism(f"RingStem{x}", rrect(-0.0095, 0.048, 0.0095, OZ - 0.012, 0.003), x, 0.014, "Optic", plane="YZ",
              bev=0.0008, segs=2)

    text("TALON-B", 0.0085, -0.110, -0.040, -0.02805, "MarkName")
    text("6.8x51  HALVARD DEFENCE", 0.0030, -0.110, -0.049, -0.02805, "MarkCal")
