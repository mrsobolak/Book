"""LONGREACH .338: bolt-action chassis sniper rifle with a 5-25x56 scope."""
from lib import *


def barrel_r(x):
    return 0.0135 - max(0.0, x - 0.25) * (0.0020 / 0.54)


def build():
    # ---- round action + bolt
    act = lathe("Action", [(-0.122, 0), (-0.122, 0.0165), (-0.120, 0.0176), (0.108, 0.0176), (0.110, 0.0165), (0.110, 0)],
                "Steel", seg=56, bev=0.0006, segs=2)
    bm = bmesh.new(); bm_prism(bm, rrect(-0.060, -0.004, 0.012, 0.015, 0.003), 0.014, 0.02); cut(act, bm)
    lathe("BoltBody", [(-0.120, 0), (-0.120, 0.0095), (0.010, 0.0095), (0.010, 0)], "BrightSteel", seg=36)
    lathe("BoltShroud", rounded_lathe_end(-0.168, -0.118, 0.0135)[:8] + [(-0.118, 0.0135), (-0.118, 0)], "Steel", seg=40,
          bev=0.0005, segs=1)
    rod("BoltHandle", (-0.100, 0.010, 0.000), (-0.108, 0.048, -0.022), 0.0042, "BrightSteel", seg=20)
    rod("BoltKnob", (-0.107, 0.044, -0.020), (-0.111, 0.064, -0.031), 0.0095, "Polymer", seg=32, rounded=True)

    # ---- aluminium chassis
    ch = prism("Chassis", path([
        ("M", -0.165, -0.010), ("L", 0.115, -0.010), ("L", 0.115, -0.044), ("L", 0.090, -0.048), ("L", 0.088, -0.068),
        ("Q", (0.088, -0.074), (0.082, -0.074), 3), ("L", 0.008, -0.074), ("Q", (0.002, -0.074), (0.001, -0.068), 3),
        ("L", 0.000, -0.058), ("Q", (-0.002, -0.080), (-0.016, -0.082), 5), ("L", -0.052, -0.080),
        ("Q", (-0.064, -0.079), (-0.068, -0.068), 5), ("L", -0.074, -0.048), ("L", -0.140, -0.044),
        ("Q", (-0.160, -0.042), (-0.165, -0.030), 4)]), 0.0, 0.040, "Paint", bev=0.0012, segs=2)
    bm = bmesh.new()
    bm_prism(bm, rrect(-0.056, -0.074, -0.006, -0.048, 0.006), 0.0, 0.05)
    bm_prism(bm, rrect(0.010, -0.014, 0.080, 0.014, 0.002), -0.050, 0.07, plane="XY")
    for s in (1, -1):
        bm_prism(bm, rrect(-0.150, -0.036, -0.082, -0.016, 0.004), s * 0.020, 0.003)
        bm_prism(bm, rrect(0.010, -0.040, 0.105, -0.016, 0.004), s * 0.020, 0.003)
    cut(ch, bm)
    bm = bmesh.new()
    bm_tube(bm, superellipse(0.026, 0.026, 0, -0.004), superellipse(0.0215, 0.0215, 0, -0.004), 0.110, 0.470)
    fe = mk("Forend", bm, "Paint", bev=0.0010, segs=2)
    bm = bmesh.new()
    for xc in (0.150, 0.200, 0.250, 0.300, 0.350, 0.400):
        bm_prism(bm, rrect(xc - 0.016, -0.0077, xc + 0.016, -0.0003, 0.0036), 0.0, 0.08)
        bm_prism(bm, rrect(xc - 0.016, -0.0037, xc + 0.016, 0.0037, 0.0036), -0.030, 0.02, plane="XY")
    for xc in (0.175, 0.225, 0.275, 0.325, 0.375, 0.425):
        for a in (45, -45):
            vs = bm_prism(bm, rrect(xc - 0.010, -0.0025, xc + 0.010, 0.0025, 0.0024), 0.0, 0.08)
            rotate_verts(bm, vs, a, "X", (0, 0, -0.004))
    cut(fe, bm)
    rail("ScopeRail", -0.150, 0.466, 0.014, zt=0.0290)
    ar_grip("Grip", -0.008, -0.011)
    ar_trigger("Trigger", -0.004, -0.012)
    prism("Mag", rrect(0.012, -0.108, 0.078, -0.020, 0.003), 0.0, 0.026, "Steel", bev=0.0008, segs=2)
    prism("MagFloor", rrect(0.008, -0.114, 0.082, -0.104, 0.003), 0.0, 0.029, "Polymer", bev=0.0014, segs=2)
    prism("MagRelease", path([("M", 0.084, -0.050), ("L", 0.094, -0.052), ("L", 0.096, -0.070), ("L", 0.090, -0.072)]),
          0.0, 0.016, "Steel", bev=0.0006, segs=2)
    selector(-0.100, -0.024, -0.0215)

    # ---- fluted barrel + triple-port brake
    lathe("Barrel", [(0.110, 0), (0.110, 0.0135), (0.250, 0.0135), (0.790, barrel_r(0.790)), (0.790, 0)], "Steel", seg=56)
    br = bpy.data.objects["Barrel"]
    bm = bmesh.new()
    for k in range(6):
        a = math.radians(30 + 60 * k)
        pts = []
        for x in (0.485, 0.760):
            R = barrel_r(x) + 0.0015
            pts.append((x, R * math.cos(a), R * math.sin(a)))
        bm_rod(bm, pts[0], pts[1], 0.0028, seg=16, rounded=True)
    cut(br, bm)
    mb = prism("Brake", rrect(-0.0170, -0.0160, 0.0170, 0.0160, 0.006), 0.826, 0.080, "Steel", plane="YZ",
               bev=0.0008, segs=2)
    bm = bmesh.new()
    bm_lathe(bm, [(0.780, 0), (0.780, 0.0058), (0.870, 0.0058), (0.870, 0)], 32, "X")
    for x0 in (0.795, 0.815, 0.835):
        bm_box(bm, x0, x0 + 0.013, 0.004, 0.03, -0.011, 0.011)
        bm_box(bm, x0, x0 + 0.013, -0.03, -0.004, -0.011, 0.011)
    for x in (0.804, 0.824, 0.844):
        bm_prism(bm, circle(x, 0.0, 0.0028, 16), 0.012, 0.012, plane="XY")
    cut(mb, bm)

    # ---- skeleton stock with cheek riser
    prism("Hinge", rrect(-0.186, -0.044, -0.163, 0.016, 0.004), 0.0, 0.034, "Paint", bev=0.0012, segs=2)
    lathe("HingePin", [(0, 0), (0, 0.0045), (0.064, 0.0045), (0.064, 0)], "Steel", seg=20, axis="Z", c=(-0.175, 0.014, -0.046))
    stk = prism("Stock", path([("M", -0.185, 0.014), ("L", -0.505, 0.014), ("Q", (-0.515, 0.014), (-0.515, 0.004), 3),
                               ("L", -0.522, -0.118), ("L", -0.470, -0.118), ("Q", (-0.380, -0.080), (-0.300, -0.055), 8),
                               ("L", -0.185, -0.042)]), 0.0, 0.030, "Paint", bev=0.0012, segs=2)
    bm = bmesh.new()
    bm_prism(bm, path([("M", -0.215, -0.002), ("L", -0.480, -0.002), ("Q", (-0.494, -0.002), (-0.494, -0.016), 4),
                       ("L", -0.497, -0.090), ("Q", (-0.497, -0.100), (-0.486, -0.098), 3), ("L", -0.300, -0.040),
                       ("Q", (-0.215, -0.030), (-0.215, -0.015), 5)]), 0.0, 0.05)
    cut(stk, bm)
    prism("CheekRiser", rrect(-0.420, 0.030, -0.240, 0.053, 0.009), 0.0, 0.034, "Polymer", bev=0.0028, segs=3)
    for x in (-0.395, -0.265):
        rod(f"RiserPost{x}", (x, 0, 0.012), (x, 0, 0.032), 0.0042, "Steel", seg=20)
    lathe("RiserKnob", [(0, 0), (0, 0.0075), (0.008, 0.0075), (0.009, 0.0065), (0.009, 0)], "Polymer", seg=32, axis="Y",
          c=(-0.330, 0.015, 0.006), bev=0.0005, segs=2)
    prism("ButtPad", rrect(-0.537, -0.125, -0.521, 0.022, 0.006), 0.0, 0.040, "Rubber", bev=0.003, segs=3)
    mono = [(0, 0), (0, 0.006), (-0.030, 0.006), (-0.030, 0.0085), (-0.042, 0.0085), (-0.042, 0.006), (-0.052, 0.006),
            (-0.054, 0.009), (-0.058, 0.009), (-0.058, 0)]
    lathe("Monopod", mono, "Steel", seg=32, axis="Z", c=(-0.458, 0, -0.100), bev=0.0004, segs=1)

    # ---- folded bipod under the forend
    prism("BipodMount", rrect(0.418, -0.044, 0.452, -0.028, 0.004), 0.0, 0.030, "Paint", bev=0.001, segs=2)
    for s in (1, -1):
        rod(f"BipodLeg{s}", (0.440, s * 0.013, -0.038), (0.640, s * 0.013, -0.041), 0.0058, "Paint", seg=20,
            bev=0.0004, segs=1)
        rod(f"BipodFoot{s}", (0.632, s * 0.013, -0.041), (0.662, s * 0.013, -0.042), 0.0070, "Rubber", seg=20, rounded=True)

    # ---- 5-25x56 scope in 34 mm rings
    SZ = 0.069
    sc = [(-0.212, 0), (-0.212, 0.0185), (-0.216, 0.0200), (-0.216, 0.0228), (-0.176, 0.0228), (-0.160, 0.0170),
          (0.090, 0.0170), (0.140, 0.0310), (0.198, 0.0310), (0.200, 0.0325), (0.210, 0.0325), (0.210, 0.0290),
          (0.202, 0.0290), (0.202, 0)]
    lathe("Scope", sc, "Optic", seg=72, c=(0, 0, SZ), bev=0.0005, segs=2)
    bm = bmesh.new()
    bm_lathe(bm, [(0.2025, 0), (0.2025, 0.0290), (0.2035, 0.0290), (0.2035, 0)], 64, "X", (0, 0, SZ))
    bm_lathe(bm, [(-0.2125, 0), (-0.2125, 0.0185), (-0.2115, 0.0185), (-0.2115, 0)], 48, "X", (0, 0, SZ))
    mk("ScopeLenses", bm, "Glass")
    ring = [(-0.190, 0.0228), (-0.190, 0.0236)]
    x = -0.188
    while x < -0.170:
        ring += [(x, 0.0236), (x + 0.0008, 0.0244), (x + 0.0022, 0.0244), (x + 0.003, 0.0236)]
        x += 0.0035
    ring += [(-0.168, 0.0236), (-0.166, 0.0222), (-0.176, 0.0222)]
    lathe("ScopeMagRing", ring, "Optic", seg=64, c=(0, 0, SZ), closed=True)
    prism("Saddle", rrect(-0.0200, SZ - 0.020, 0.0200, SZ + 0.020, 0.008), 0.0, 0.070, "Optic", plane="YZ",
          bev=0.0014, segs=2)
    tur = [(0, 0), (0, 0.0125), (0.004, 0.0125)]
    z = 0.004
    while z < 0.017:
        tur += [(z, 0.0140), (z + 0.0012, 0.0140), (z + 0.0018, 0.0133)]
        z += 0.0018
    tur += [(0.019, 0.0133), (0.021, 0.0118), (0.021, 0)]
    lathe("ElevTurret", tur, "Optic", seg=48, axis="Z", c=(0.0, 0, SZ + 0.0195))
    lathe("WindTurret", tur, "Optic", seg=48, axis="Y", c=(0.0, 0.0195, SZ))
    bm = bmesh.new(); vs = bm_lathe(bm, [(0, 0), (0, 0.0115), (0.012, 0.0115), (0.014, 0.0100), (0.014, 0)], 48, "Y",
                                    (0.0, 0.0195, SZ)); mirror_y(vs)
    mk("ParallaxKnob", bm, "Optic", bev=0.0004, segs=1)
    bm = bmesh.new()
    for x in (-0.100, 0.060):
        bm_tube(bm, circle(0, SZ, 0.0220, 56), circle(0, SZ, 0.0170, 56), x - 0.008, x + 0.008)
    mk("Rings", bm, "Optic", bev=0.0006, segs=2)
    base = [(-0.0125, 0.0250), (0.0125, 0.0250), (0.0125, 0.034), (0.010, SZ - 0.0205), (-0.010, SZ - 0.0205),
            (-0.0125, 0.034)]
    for x in (-0.100, 0.060):
        prism(f"RingBase{x}", base, x, 0.016, "Optic", plane="YZ", bev=0.0008, segs=2)
        lathe(f"CrossBolt{x}", [(0, 0), (0, 0.0055), (0.004, 0.0055), (0.004, 0)], "Steel", seg=6, axis="Y",
              c=(x, 0.0125, 0.030))
    text("LONGREACH .338", 0.0060, 0.058, -0.030, -0.01855, "MarkName")
    text("NORTHLINE PRECISION", 0.0028, 0.058, -0.037, -0.01855, "MarkMaker")
    text("SN LR-338-0042", 0.0028, 0.058, -0.030, 0.01855, "MarkSerial")
