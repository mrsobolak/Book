"""VESPA-9: compact 9x19 mm submachine gun with a side-folding skeleton stock."""
from lib import *


def build():
    # ---- upper receiver + full-length top rail
    up = prism("Upper", rrect(-0.125, -0.012, 0.125, 0.021, 0.003), 0.0, 0.032, "Paint", bev=0.0008, segs=2)
    bm = bmesh.new()
    bm_prism(bm, rrect(-0.020, -0.004, 0.035, 0.0125, 0.002), 0.017, 0.022)          # ejection port
    for side in (1, -1):
        bm_prism(bm, rrect(-0.110, 0.001, -0.045, 0.0135, 0.003), side * 0.0170, 0.004)
        bm_prism(bm, rrect(0.050, -0.006, 0.112, 0.0135, 0.003), side * 0.0170, 0.004)
    cut(up, bm)
    rail("TopRail", -0.120, 0.215, 0.019)
    lathe("BoltFace", [(-0.030, 0), (-0.030, 0.0085), (0.034, 0.0085), (0.034, 0)], "BrightSteel", seg=32,
          c=(0, 0, 0.004), bev=0.0004, segs=1)

    # ---- handguard
    bm = bmesh.new()
    bm_tube(bm, superellipse(0.0205, 0.021, 0, -0.001), superellipse(0.0165, 0.017, 0, -0.001), 0.125, 0.215)
    hg = mk("Handguard", bm, "Paint", bev=0.0009, segs=2)
    bm = bmesh.new()
    for xc in (0.150, 0.190):
        bm_prism(bm, rrect(xc - 0.014, -0.0060, xc + 0.014, 0.0012, 0.0034), 0.0, 0.06)
    bm_prism(bm, rrect(0.156, -0.0037, 0.184, 0.0037, 0.0034), -0.022, 0.02, plane="XY")
    cut(hg, bm)
    prism("HandStop", path([("M", 0.186, -0.018), ("L", 0.212, -0.018), ("Q", (0.216, -0.018), (0.215, -0.024), 3),
                            ("L", 0.212, -0.040), ("Q", (0.210, -0.045), (0.205, -0.043), 3), ("L", 0.186, -0.024)]),
          0.0, 0.018, "Polymer", bev=0.002, segs=2)

    # ---- barrel + slotted flash can
    lathe("Barrel", [(0.10, 0), (0.10, 0.0075), (0.232, 0.0075), (0.232, 0)], "Steel", seg=32)
    can = lathe("FlashCan", [(0.228, 0), (0.228, 0.0100), (0.231, 0.0108), (0.258, 0.0108), (0.262, 0.0095),
                             (0.262, 0.0048), (0.256, 0.0044), (0.236, 0.0044), (0.236, 0)], "Steel", seg=40,
                bev=0.0004, segs=2)
    bm = bmesh.new()
    for k in range(6):
        vs = bm_box(bm, 0.238, 0.2555, -0.0015, 0.0015, 0.004, 0.02)
        rotate_verts(bm, vs, 30 + 60 * k, "X", (0, 0, 0))
    cut(can, bm)

    # ---- cocking tube on the left with a folding knob
    lathe("CockingTube", rounded_lathe_end(0.118, 0.214, 0.0055), "Paint", seg=24, c=(0, -0.020, 0.013),
          bev=0.0003, segs=1)
    rod("CockingArm", (0.205, -0.021, 0.013), (0.205, -0.036, 0.016), 0.0032, "Steel", seg=16)
    rod("CockingKnob", (0.205, -0.034, 0.0158), (0.205, -0.047, 0.0172), 0.0052, "Polymer", seg=24, rounded=True)

    # ---- polymer lower with integrated grip, guard and magwell
    lower = path([
        ("M", -0.125, -0.0123), ("L", 0.075, -0.0123), ("L", 0.075, -0.030), ("L", 0.070, -0.040),
        ("L", 0.062, -0.070), ("Q", (0.062, -0.078), (0.054, -0.078), 3), ("L", 0.018, -0.078),
        ("Q", (0.012, -0.078), (0.012, -0.072), 3), ("L", 0.010, -0.058),
        ("Q", (0.008, -0.074), (-0.006, -0.074), 5), ("L", -0.036, -0.072), ("Q", (-0.046, -0.071), (-0.050, -0.060), 5),
        ("L", -0.052, -0.052), ("Q", (-0.056, -0.075), (-0.060, -0.085), 5), ("Q", (-0.056, -0.098), (-0.064, -0.108), 5),
        ("Q", (-0.060, -0.122), (-0.068, -0.134), 5), ("Q", (-0.070, -0.146), (-0.080, -0.147), 4),
        ("L", -0.100, -0.146), ("Q", (-0.112, -0.145), (-0.112, -0.134), 4), ("L", -0.094, -0.060),
        ("Q", (-0.090, -0.046), (-0.100, -0.040), 4), ("Q", (-0.112, -0.036), (-0.118, -0.030), 4), ("L", -0.125, -0.022),
    ])
    lo = prism("Lower", lower, 0.0, 0.028, "Polymer", bev=0.0014, segs=2)
    bm = bmesh.new()
    bm_prism(bm, rrect(0.016, -0.0115, 0.059, 0.0115, 0.002), -0.056, 0.07, plane="XY")
    bm_prism(bm, rrect(-0.044, -0.067, 0.004, -0.040, 0.006), 0.0, 0.04)
    cut(lo, bm)
    panel = path([("M", -0.062, -0.074), ("L", -0.095, -0.071), ("L", -0.106, -0.126), ("Q", (-0.106, -0.134), (-0.098, -0.134), 3),
                  ("L", -0.076, -0.134), ("Q", (-0.069, -0.133), (-0.070, -0.126), 3), ("Q", (-0.062, -0.110), (-0.066, -0.100), 4),
                  ("Q", (-0.058, -0.088), (-0.062, -0.074), 4)])
    bm = bmesh.new()
    for s in (1, -1):
        bm_prism(bm, panel, s * 0.0142, 0.0014)
    mk("GripPanels", bm, "Grip", bev=0.0004, segs=1)

    trig = path([("M", -0.026, -0.041), ("L", -0.020, -0.041), ("Q", (-0.017, -0.052), (-0.019, -0.063), 5),
                 ("Q", (-0.021, -0.066), (-0.024, -0.063), 3), ("L", -0.026, -0.052)])
    prism("Trigger", trig, 0.0, 0.0045, "Steel", bev=0.0005, segs=2)
    lathe("SelectorHub", [(0, 0), (0, 0.0055), (-0.0022, 0.0055), (-0.0028, 0.0046), (-0.0028, 0)], "Steel", seg=28,
          axis="Y", c=(-0.078, -0.0140, -0.022), bev=0.0003, segs=1)
    prism("SelectorLever", rrect(-0.079, -0.0245, -0.060, -0.0195, 0.0024), -0.0168, 0.0016, "Steel", bev=0.0003, segs=1)
    pins("Pins", [(0.066, -0.018, 0.0035), (-0.115, -0.018, 0.0035), (-0.022, -0.030, 0.003)], 0.0140)
    text("VESPA-9", 0.0052, 0.036, -0.036, -0.01405, "MarkName")
    text("9x19 mm", 0.0026, 0.036, -0.044, -0.01405, "MarkCal")
    text("KESTREL ARMS", 0.0030, 0.036, -0.036, 0.01405, "MarkMaker")
    text("SAFE", 0.0022, -0.058, -0.017, -0.01405, "MarkSafe")
    text("AUTO", 0.0022, -0.096, -0.026, -0.01405, "MarkAuto")

    # ---- straight 30-round magazine with round-count holes
    mag = prism("Mag", [(0.018, -0.020), (0.056, -0.020), (0.069, -0.212), (0.031, -0.212)], 0.0, 0.0215, "Polymer",
                bev=0.0012, segs=2)
    bm = bmesh.new()
    for k in range(5):
        z = -0.095 - 0.025 * k
        x = 0.018 + 0.013 * ((-0.020 - z) / 0.192) + 0.0065
        for s in (1, -1):
            bm_prism(bm, circle(x, z, 0.0021, 16), s * 0.0108, 0.003)
    cut(mag, bm)
    prism("MagFloor", rrect(0.028, -0.2215, 0.073, -0.2105, 0.003), 0.0, 0.0255, "Polymer", bev=0.0015, segs=2,
          taper=None)

    # ---- side-folding skeleton stock (extended)
    prism("Hinge", rrect(-0.142, -0.032, -0.123, 0.019, 0.004), 0.0, 0.030, "Paint", bev=0.0012, segs=2)
    lathe("HingePin", [(0, 0), (0, 0.004), (0.036, 0.004), (0.036, 0)], "Steel", seg=20, axis="Z", c=(-0.134, 0.011, -0.030))
    rod("StrutTop", (-0.140, 0, 0.010), (-0.350, 0, 0.012), 0.0065, "Paint", seg=24, bev=0.0004, segs=1)
    rod("StrutLow", (-0.138, 0, -0.024), (-0.346, 0, -0.074), 0.0055, "Paint", seg=24, bev=0.0004, segs=1)
    prism("ButtFrame", rrect(-0.352, -0.090, -0.340, 0.024, 0.004), 0.0, 0.030, "Paint", bev=0.0012, segs=2)
    prism("ButtPad", rrect(-0.364, -0.098, -0.350, 0.029, 0.006), 0.0, 0.036, "Rubber", bev=0.003, segs=3)
    prism("CheekPad", rrect(-0.300, 0.002, -0.215, 0.025, 0.006), 0.0, 0.030, "Polymer", bev=0.003, segs=3)
    lathe("StockQD", [(0, 0.0032), (0, 0.006), (-0.0018, 0.006), (-0.0018, 0.0032)], "Steel", seg=28, axis="Y",
          c=(-0.133, -0.015, -0.006), closed=True)

    # ---- mini reflex sight (open emitter)
    prism("RDSBase", rrect(-0.036, 0.0245, 0.012, 0.0345, 0.003), 0.0, 0.026, "Optic", bev=0.0010, segs=2)
    hood = prism("RDSHood", rrect(-0.0135, 0.029, 0.0135, 0.060, 0.007), 0.0035, 0.015, "Optic", plane="YZ",
                 bev=0.0009, segs=2)
    bm = bmesh.new(); bm_prism(bm, rrect(-0.0108, 0.0335, 0.0108, 0.0570, 0.005), 0.0035, 0.03, plane="YZ")
    cut(hood, bm)
    prism("RDSGlass", rrect(-0.011, 0.0333, 0.011, 0.0572, 0.005), 0.0035, 0.0012, "Glass", plane="YZ")
    prism("RDSEmitter", rrect(-0.030, 0.0335, -0.020, 0.0385, 0.002), 0.0, 0.010, "Optic", bev=0.0008, segs=2)
    lathe("RDSDot", [(0.0027, 0), (0.0027, 0.0008), (0.0029, 0.0008), (0.0029, 0)], "Reticle", seg=12, c=(0, 0, 0.0455))
    lathe("RDSBattery", [(0, 0), (0, 0.0055), (0.0022, 0.0055), (0.0028, 0.0046), (0.0028, 0)], "Steel", seg=28,
          axis="Y", c=(-0.016, 0.013, 0.0295), bev=0.0003, segs=1)
