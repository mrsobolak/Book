"""MAGISTRATE: six-shot stainless .357 Magnum revolver with walnut grips."""
from lib import *

CZ = -0.0105   # cylinder axis (top chamber lines up with the bore at z = 0)


def build():
    # ---- full-lug barrel with vented rib
    bl = prism("Barrel", path([("M", 0.042, 0.0115), ("L", 0.198, 0.0115), ("Q", (0.201, 0.0115), (0.201, 0.0085), 3),
                               ("L", 0.201, -0.019), ("Q", (0.201, -0.022), (0.198, -0.022), 3), ("L", 0.060, -0.024),
                               ("L", 0.046, -0.032), ("L", 0.042, -0.032)]), 0.0, 0.020, "Stainless", bev=0.0014, segs=2)
    bm = bmesh.new()
    bm_lathe(bm, [(0.170, 0), (0.170, 0.0046), (0.210, 0.0046), (0.210, 0)], 32, "X")
    bm_lathe(bm, [(0.038, 0), (0.038, 0.0046), (0.062, 0.0046), (0.062, 0)], 24, "X", (0, 0, CZ))
    cut(bl, bm)
    rib = prism("Rib", rrect(0.044, 0.0105, 0.199, 0.0165, 0.0015), 0.0, 0.0105, "Stainless", bev=0.0006, segs=2)
    bm = bmesh.new()
    x = 0.060
    while x < 0.185:
        bm_box(bm, x, x + 0.0105, -0.01, 0.01, 0.0100, 0.0142)
        x += 0.020
    cut(rib, bm)
    prism("FrontSight", [(0.170, 0.016), (0.193, 0.016), (0.193, 0.027), (0.186, 0.027)], 0.0, 0.0042, "Stainless",
          bev=0.0004, segs=1)
    prism("SightInsert", rrect(0.1862, 0.0205, 0.1920, 0.0262, 0.0008), 0.0, 0.0046, "ShellHull")
    prism("RearSight", [(-0.0065, 0.020), (0.0065, 0.020), (0.0065, 0.028), (0.0015, 0.028), (0.0015, 0.0245),
                        (-0.0015, 0.0245), (-0.0015, 0.028), (-0.0065, 0.028)], -0.050, 0.010, "Steel", plane="YZ",
          bev=0.0004, segs=1)

    # ---- frame
    fr = prism("Frame", path([
        ("M", -0.058, 0.021), ("L", 0.046, 0.021), ("L", 0.046, -0.030), ("L", 0.022, -0.035), ("L", 0.010, -0.037),
        ("Q", (0.012, -0.064), (-0.010, -0.066), 5), ("L", -0.030, -0.064), ("Q", (-0.042, -0.062), (-0.042, -0.045), 4),
        ("L", -0.048, -0.040), ("L", -0.066, -0.100), ("L", -0.086, -0.100), ("L", -0.082, -0.030),
        ("Q", (-0.080, -0.004), (-0.068, 0.010), 4), ("Q", (-0.064, 0.021), (-0.058, 0.021), 3)]),
        0.0, 0.028, "Stainless", bev=0.0012, segs=2)
    bm = bmesh.new()
    bm_prism(bm, rrect(-0.021, -0.032, 0.043, 0.0105, 0.003), 0.0, 0.05)
    bm_prism(bm, rrect(-0.036, -0.060, 0.004, -0.040, 0.008), 0.0, 0.05)
    bm_box(bm, -0.074, -0.050, -0.0045, 0.0045, 0.004, 0.030)
    cut(fr, bm)

    # ---- fluted cylinder with loaded chambers
    cy = lathe("Cylinder", [(-0.019, 0), (-0.019, 0.0190), (-0.017, 0.0206), (0.039, 0.0206), (0.041, 0.0190), (0.041, 0)],
               "Stainless", seg=72, c=(0, 0, CZ), bev=0.0004, segs=1)
    bm = bmesh.new()
    for k in range(6):
        a = math.radians(30 + 60 * k)
        bm_rod(bm, (-0.006, 0.0218 * math.cos(a), CZ + 0.0218 * math.sin(a)),
               (0.034, 0.0218 * math.cos(a), CZ + 0.0218 * math.sin(a)), 0.0043, seg=20, rounded=True)
        a = math.radians(90 + 60 * k)
        bm_lathe(bm, [(0.028, 0), (0.028, 0.0046), (0.046, 0.0046), (0.046, 0)], 20, "X",
                 (0, 0.0105 * math.cos(a), CZ + 0.0105 * math.sin(a)))
    cut(cy, bm)
    bm = bmesh.new()
    for k in range(6):
        a = math.radians(90 + 60 * k)
        prof = [(0.026, 0), (0.026, 0.0044), (0.034, 0.0044), (0.036, 0.0036), (0.037, 0.0018), (0.037, 0)]
        bm_lathe(bm, prof, 16, "X", (0, 0.0105 * math.cos(a), CZ + 0.0105 * math.sin(a)))
    mk("Bullets", bm, "Copper")
    lathe("EjectorRod", [(0.036, 0), (0.036, 0.0028), (0.050, 0.0028), (0.050, 0.0036), (0.056, 0.0036), (0.057, 0.0030),
                         (0.057, 0)], "Stainless", seg=24, c=(0, 0, CZ))
    lathe("CylinderPin", [(-0.020, 0), (-0.020, 0.0036), (-0.017, 0.0036), (-0.017, 0)], "Stainless", seg=24, c=(0, 0, CZ))

    # ---- lockwork: hammer, trigger, latch
    ham = path([("M", -0.064, 0.002), ("L", -0.055, 0.004), ("L", -0.055, 0.018), ("Q", (-0.060, 0.028), (-0.072, 0.031), 5),
                ("L", -0.083, 0.034), ("Q", (-0.088, 0.034), (-0.086, 0.029), 3), ("L", -0.075, 0.022), ("L", -0.066, 0.010)])
    hm = prism("Hammer", ham, 0.0, 0.0078, "Steel", bev=0.0006, segs=2)
    bm = bmesh.new()
    for i in range(5):
        vs = bm_box(bm, -0.084 + i * 0.0028, -0.0828 + i * 0.0028, -0.01, 0.01, 0.028, 0.040)
        rotate_verts(bm, vs, -18, "Y", (-0.080, 0, 0.031))
    cut(hm, bm)
    prism("Trigger", path([("M", -0.020, -0.035), ("L", -0.011, -0.035), ("Q", (-0.007, -0.048), (-0.012, -0.058), 5),
                           ("Q", (-0.015, -0.061), (-0.018, -0.058), 3), ("L", -0.021, -0.046)]), 0.0, 0.0062, "Steel",
          bev=0.0008, segs=2)
    lt = prism("Latch", rrect(-0.036, -0.001, -0.020, 0.008, 0.002), -0.0150, 0.0030, "Steel", bev=0.0005, segs=1)
    bm = bmesh.new()
    for i in range(5):
        bm_box(bm, -0.034 + i * 0.003, -0.0328 + i * 0.003, -0.02, -0.0160, -0.004, 0.012)
    cut(lt, bm)
    pins("FramePins", [(-0.070, -0.012, 0.0022), (-0.030, -0.030, 0.0022)], 0.0140, mat="Stainless")

    # ---- walnut finger-groove grips with medallions
    grip = path([("M", -0.048, -0.038), ("Q", (-0.060, -0.030), (-0.084, -0.026), 5), ("Q", (-0.100, -0.040), (-0.108, -0.090), 8),
                 ("Q", (-0.114, -0.130), (-0.098, -0.140), 6), ("L", -0.066, -0.140), ("Q", (-0.056, -0.138), (-0.058, -0.126), 3),
                 ("Q", (-0.048, -0.114), (-0.056, -0.104), 5), ("Q", (-0.046, -0.092), (-0.054, -0.082), 5),
                 ("Q", (-0.042, -0.070), (-0.050, -0.060), 5), ("Q", (-0.042, -0.050), (-0.048, -0.038), 4)])
    prism("Grips", grip, 0.0, 0.036, "Wood", bev=0.0055, segs=3)
    bm = bmesh.new()
    for s in (1, -1):
        vs = bm_lathe(bm, [(0, 0), (0, 0.0060), (0.0006, 0.0060), (0.0010, 0.0050), (0.0010, 0)], 32, "Y", (-0.083, 0.0178, -0.066))
        if s < 0: mirror_y(vs)
    mk("Medallions", bm, "Brass")
    bm = bmesh.new()
    for s in (1, -1):
        vs = bm_lathe(bm, [(0, 0), (0, 0.0028), (0.0008, 0.0028), (0.0010, 0.0022), (0.0010, 0)], 20, "Y", (-0.086, 0.0176, -0.104))
        if s < 0: mirror_y(vs)
    mk("GripScrew", bm, "Stainless")

    text("MAGISTRATE", 0.0056, 0.122, -0.0045, -0.01005, "MarkName")
    text(".357 MAGNUM", 0.0032, 0.122, -0.0115, -0.01005, "MarkCal")
    text("HALVARD DEFENCE", 0.0028, 0.122, -0.0060, 0.01005, "MarkMaker")
