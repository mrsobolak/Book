    bm = bmesh.new()
    for x in xs:
        bm_lathe(bm, [(-0.03, 0), (-0.03, 0.0112), (0.03, 0.0112), (0.03, 0)], 32, "Z", (x, sy, 0))
    cut(hold, bm)
    hull, head = bmesh.new(), bmesh.new()
    for x in xs:
        bm_lathe(hull, [(-0.026, 0), (-0.026, 0.0104), (0.022, 0.0104), (0.0245, 0.0098), (0.0255, 0.0075),
                        (0.0258, 0)], 32, "Z", (x, sy, 0))
        bm_lathe(head, [(-0.041, 0), (-0.041, 0.0112), (-0.039, 0.0112), (-0.038, 0.0106), (-0.025, 0.0106),
                        (-0.025, 0)], 32, "Z", (x, sy, 0))
    mk("ShellHulls", hull, "ShellHull", bev=0.0003, segs=1)
    mk("ShellHeads", head, "Brass", bev=0.0003, segs=1)

    text("HOLLOWPOINT 12", 0.0060, -0.050, -0.022, 0.01805, "MarkName")
    text("12 GA  3 IN CHAMBER", 0.0030, -0.050, -0.029, 0.01805, "MarkCal")
