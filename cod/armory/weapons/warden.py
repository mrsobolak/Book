"""WARDEN .45: full-size striker-fired pistol with tritium night sights."""
from lib import *


def build():
    # ---- slide
    sec = [(-0.012, -0.010), (0.012, -0.010), (0.012, 0.011), (0.0085, 0.017), (-0.0085, 0.017), (-0.012, 0.011)]
    sl = prism("Slide", sec, -0.008, 0.184, "Paint", plane="YZ", bev=0.0008, segs=2)
    bm = bmesh.new()
    bm_prism(bm, [(0.070, 0.022), (0.088, 0.022), (0.088, 0.003)], 0.0, 0.04)                       # sloped nose
    for i in range(9):                                                                              # rear serrations
        x = -0.097 + i * 0.0042
        for s in (1, -1):
            vs = bm_box(bm, x, x + 0.0017, 0.0103 if s > 0 else -0.02, 0.02 if s > 0 else -0.0103, -0.006, 0.0135)
            rotate_verts(bm, vs, -12, "Y", (x, 0, 0))
    for i in range(6):                                                                              # front serrations
        x = 0.044 + i * 0.0042
        for s in (1, -1):
            vs = bm_box(bm, x, x + 0.0017, 0.0103 if s > 0 else -0.02, 0.02 if s > 0 else -0.0103, -0.006, 0.0115)
            rotate_verts(bm, vs, -12, "Y", (x, 0, 0))
    bm_prism(bm, rrect(-0.028, -0.005, 0.020, 0.016, 0.002), 0.017, 0.02, plane="XY")              # ejection port
    bm_lathe(bm, [(0.06, 0), (0.06, 0.0077), (0.1, 0.0077), (0.1, 0)], 32, "X")                     # muzzle bore
    cut(sl, bm)
    prism("BarrelHood", rrect(-0.028, 0.001, 0.020, 0.0125, 0.0015), 0.0, 0.0144, "Steel", bev=0.0005, segs=1)
    lathe("Barrel", [(0.02, 0), (0.02, 0.0072), (0.0845, 0.0072), (0.0855, 0.0064), (0.0855, 0.0058), (0.074, 0.0058),
                     (0.074, 0)], "Steel", seg=32, bev=0.0003, segs=1)

    # sights with tritium inserts
    rear = [(-0.011, 0.016), (0.011, 0.016), (0.011, 0.0255), (0.0022, 0.0255), (0.0022, 0.0215), (-0.0022, 0.0215),
            (-0.0022, 0.0255), (-0.011, 0.0255)]
    prism("RearSight", rear, -0.089, 0.012, "Steel", plane="YZ", bev=0.0006, segs=2)
    prism("FrontSight", rrect(-0.0019, 0.016, 0.0019, 0.0248, 0.0008), 0.075, 0.006, "Steel", plane="YZ",
          bev=0.0004, segs=1)
    bm = bmesh.new()
    for y in (-0.0066, 0.0066):
        bm_lathe(bm, [(-0.0952, 0), (-0.0952, 0.0014), (-0.0948, 0.0014), (-0.0948, 0)], 16, "X", (0, y, 0.0212))
    bm_lathe(bm, [(0.0718, 0), (0.0718, 0.0013), (0.0722, 0.0013), (0.0722, 0)], 16, "X", (0, 0, 0.0218))
    mk("Tritium", bm, "Tritium")

    # ---- polymer frame
    frame = path([
        ("M", -0.098, -0.0102), ("L", 0.078, -0.0102), ("L", 0.078, -0.024), ("Q", (0.078, -0.029), (0.073, -0.029), 3),
        ("L", 0.052, -0.029), ("L", 0.052, -0.036), ("L", 0.054, -0.052), ("Q", (0.054, -0.060), (0.046, -0.060), 3),
        ("L", 0.010, -0.060), ("Q", (-0.005, -0.060), (-0.012, -0.048), 4), ("Q", (-0.028, -0.060), (-0.030, -0.070), 4),
        ("Q", (-0.026, -0.085), (-0.036, -0.095), 5), ("Q", (-0.034, -0.110), (-0.042, -0.120), 5), ("L", -0.046, -0.133),
        ("L", -0.093, -0.133), ("Q", (-0.098, -0.133), (-0.097, -0.126), 3), ("L", -0.080, -0.040),
        ("Q", (-0.078, -0.032), (-0.090, -0.028), 4), ("Q", (-0.104, -0.022), (-0.104, -0.014), 4),
    ])
    fr = prism("Frame", frame, 0.0, 0.028, "Polymer", bev=0.0014, segs=2)
    bm = bmesh.new()
    bm_prism(bm, rrect(-0.006, -0.054, 0.046, -0.033, 0.006), 0.0, 0.04)
    bm_prism(bm, rrect(-0.091, -0.0108, -0.051, 0.0108, 0.002), -0.140, 0.02, plane="XY")
    cut(fr, bm)
    rail("DustRail", 0.030, 0.074, -0.026, zt=-0.0345, mat="Polymer", flip=True)
    lathe("GuideRod", [(0.070, 0), (0.070, 0.0036), (0.0795, 0.0036), (0.0795, 0)], "Steel", seg=24, c=(0, 0, -0.018))
    panel = path([("M", -0.031, -0.058), ("Q", (-0.024, -0.080), (-0.034, -0.094), 5), ("Q", (-0.032, -0.108), (-0.040, -0.118), 5),
                  ("L", -0.044, -0.127), ("L", -0.089, -0.127), ("L", -0.076, -0.048), ("Q", (-0.056, -0.046), (-0.031, -0.058), 4)])
    bm = bmesh.new()
    for s in (1, -1):
        bm_prism(bm, panel, s * 0.0142, 0.0014)
    mk("GripTexture", bm, "Grip", bev=0.0004, segs=1)
    prism("MagBase", rrect(-0.097, -0.142, -0.044, -0.131, 0.003), 0.0, 0.029, "Polymer", bev=0.0015, segs=2)

    # controls
    trig = path([("M", 0.013, -0.033), ("L", 0.019, -0.033), ("Q", (0.022, -0.045), (0.018, -0.054), 5),
                 ("Q", (0.016, -0.057), (0.013, -0.054), 3), ("Q", (0.012, -0.044), (0.013, -0.033), 4)])
    prism("Trigger", trig, 0.0, 0.007, "Polymer", bev=0.0008, segs=2)
    prism("TriggerBlade", path([("M", 0.0165, -0.040), ("L", 0.0208, -0.040), ("Q", (0.0212, -0.047), (0.0192, -0.051), 3),
                                ("L", 0.0168, -0.051)]), 0.0, 0.0018, "Steel", bev=0.0003, segs=1)
    prism("SlideStop", path([("M", -0.032, -0.0118), ("L", 0.004, -0.0118), ("Q", (0.008, -0.0118), (0.008, -0.016), 3),
                             ("L", 0.006, -0.0200), ("L", -0.028, -0.0190)]), -0.0146, 0.0018, "Steel", bev=0.0004, segs=1)
    prism("Takedown", rrect(0.010, -0.021, 0.021, -0.0145, 0.0015), -0.0145, 0.0018, "Steel", bev=0.0004, segs=1)
    prism("MagRelease", rrect(-0.023, -0.045, -0.011, -0.036, 0.002), 0.0, 0.0296, "Polymer", bev=0.0008, segs=2)
    pins("Pins", [(0.008, -0.020, 0.0022), (-0.068, -0.020, 0.0022)], 0.0140)
    text("WARDEN", 0.0050, -0.022, -0.0035, -0.01205, "MarkName")
    text(".45 AUTO", 0.0030, 0.020, -0.0035, -0.01205, "MarkCal")
    text("KESTREL ARMS", 0.0028, -0.010, -0.0035, 0.01205, "MarkMaker")
